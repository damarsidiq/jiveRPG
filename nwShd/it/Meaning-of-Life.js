var shdtxt=`Quali film vengono in mente se qualcuno ti chiede " come trovo significato e scopo per la vita che sto vivendo?!".
La ricerca di significato e scopo è una delle correnti più antiche della narrazione.
E diversi registi lo hanno illuminato attraverso toni selvaggiamente diversi.
Tragedia, meraviglia, assurdità, persino commedia.
Ecco alcuni film che emergono quando questa domanda viene sussurrata nel buio:.
1. "Ikiru" (1952, Akira Kurosawa).
Un funzionario viene a sapere che sta morendo e passa il suo tempo rimanente cercando di fare un atto significativo.
Kurosawa fa sentire la burocrazia come una lenta morte spirituale, poi mostra come anche un singolo parco giochi può riscattarla.
2. The Truman Show (1998, Peter Weir)
Un uomo scopre che tutta la sua vita è un elaborato televisore.
È una parabola sul significato costruito contro il significato scelto - il coraggio di uscire dalla sceneggiatura.
3. L'albero della vita (2011, Terrence Malick)
Parte preghiera, parte memoria.
Inizia con la morte di un bambino, poi si espande fino alla nascita dell'universo.
Malick suggerisce che il significato non è qualcosa che inventiamo, ma qualcosa che riconosciamo nei momenti di grazia.
4. Il giorno della marmotta (Groundhog Day), regia di Harold Ramis (1993)
Una commedia che si insinua come filosofia buddista.
Rivivendo lo stesso giorno all'infinito, il protagonista impara che il significato non deriva dalla novità.
Ma dal diventare veramente svegli per gli altri.
5. "Synecdoche, New York" (2008, Charlie Kaufman).
Il tentativo di un drammaturgo di ricreare la sua vita in un magazzino diventa un labirinto ricorsivo di creazione di significato.
È doloroso, divertente e terribilmente onesto riguardo alla nostra ossessione per la comprensione di noi stessi.
6. "Anima" (2020, Pixar).
Un musicista muore prima della sua "grande occasione".
E impara che lo scopo potrebbe non riguardare ciò che "fai".
Ma quanto profondamente "vivi".
È esistenzialismo per tutte le età.
7. Una vita nascosta (A Hidden Life), regia di Terrence Malick (2019)
La vera storia di Franz Jägerstätter, che si rifiutò di giurare fedeltà a Hitler.
Lo scopo qui diventa chiarezza morale.
Vivere in modo significativo significa scegliere la verità anche quando non si vede.
8. Wings of Desire (Wim Wenders, 1987)
Gli angeli vagano su Berlino, osservatori invisibili del dolore e della gioia umana.
Fino a quando non si desidera "diventare" umani.
Significato, Wenders implica, vive nell'incarnazione, nel contatto, nel rischio.
9. Into the Wild, regia di Sean Penn (2007)
Un uomo abbandona la civiltà per trovare la purezza nella natura.
Il suo viaggio è sia una critica del significato materiale che un promemoria del fatto che l'isolamento non è mai la risposta completa.
10. È una vita meravigliosa (It's a Wonderful Life), regia di Frank Capra (1946)
Rassicurazione cinematografica che la propria esistenza ordinaria " è " una vita di scopo.
Ognuno di questi film dà una risposta diversa alla domanda " Cosa dà senso alla vita?”.
Alcuni puntano all'amore.
Altri alla creazione, al servizio, alla consapevolezza o al coraggio di affrontare l'assurdità.`;