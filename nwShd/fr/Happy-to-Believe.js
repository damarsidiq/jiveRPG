var shdtxt=`Je suis en train de lire le verset 107 de la sourate Al-An'am du Coran.
« Si Allah l'avait voulu, ils n'auraient pas pris de faux dieux ».
Il y a une certaine confusion sémantique si l'on examine ce verset de près en le comparant au verset 148.
« Si Allah l’avait voulu, nous ne lui aurions pas attribué d’associés… “C’est ainsi que leurs ancêtres ont avancé de faux arguments” ».
Je veux dire, en quoi s’agirait-il alors d’un faux argument ?
Cela a peut-être un rapport avec l’action, la volonté et le dessein de Dieu pour chaque chemin correspondant ?
Mais c’est là une exposition très complexe et révélatrice du mécanisme de la foi d’une personne par rapport à la « réalité » ou à la « vie ».
Tu ne passes pas à côté de quelque chose d’évident. La tension est bien réelle, et le Coran la met en avant délibérément au lieu de l’édulcorer comme le ferait une mauvaise brochure théologique.
Voici l’idée centrale, dépouillée de tout brouillard mystique.
6:107 « Si Allah l’avait voulu, ils n’auraient pas commis de shirk. ».
C’est une affirmation de puissance et d’ampleur.
Il s’agit de la réalité ontologique.
Rien ne se produit en dehors de la volonté englobante de Dieu.
S’Il avait voulu un univers où le shirk était métaphysiquement impossible, cet univers existerait à la place de celui-ci.
Fin de l’histoire.
6:148 « Si Allah l’avait voulu, nous n’aurions pas associé d’autres divinités… pas plus que nos pères. »
Puis Dieu qualifie cet argument de faux.
Alors pourquoi la même phrase est-elle vraie à un endroit et fausse à un autre ?
Parce que ce n’est pas la phrase qui constitue l’argument, mais l’usage qui en est fait.
C’est la distinction que le Coran vous oblige discrètement à remarquer.
Il existe deux niveaux de volonté qui opèrent simultanément, que cela plaise ou non aux gens :
1. La volonté universelle / créatrice (irādah kawniyyah).
Ce que Dieu permet qu’il se produise dans la réalité.
Cela inclut la mécréance, la croyance, la gravité, la mort, les moustiques et les mauvais arguments.
2. La volonté morale / législative (irādah shar‘iyyah).
Ce que Dieu ordonne, aime et dont Il tient les gens pour responsables.
La foi, la justice, l’honnêteté, le repentir.
Dans 6:107, Dieu s’exprime depuis le niveau 1 :
> « Ne croyez pas que cela M’ait échappé. »
Dans 6:148, les mécréants abusent du niveau 1 pour annuler le niveau 2 :.
> « Puisque Dieu l’a permis, nous sommes innocents. ».
C’est cette manœuvre qui est qualifiée de fausse.
En quoi s’agit-il précisément d’un faux argument ?
Ils commettent trois actes illégitimes à la fois. 
1. Confondre permission et approbation.
Autoriser une action ≠ l’approuver.
L’oxygène permet l’incendie criminel. Cela ne rend pas le feu moralement neutre.
2. Utiliser la connaissance divine pour effacer le libre arbitre humain.
Le fait que Dieu connaisse ou autorise votre choix ne transforme pas votre choix en Son action.
C’est toujours vous qui avez bandé l’arc. C’est toujours vous qui avez lâché la flèche.
3. Argumenter après coup plutôt qu’avant.
Remarquez le schéma du Coran :
Personne ne dit : « Si Allah le veut, je commettrai le shirk demain. »
Ils le disent après avoir été mis au pied du mur.
Ce n’est pas de la métaphysique. C’est de la gestion de crise.
Le Coran dénonce donc cette manœuvre comme intellectuellement malhonnête, et non comme philosophiquement profonde.
— L’action est l’axe manquant que vous aviez pressenti. Vous aviez raison de vous concentrer sur l’action.
Le Coran traite la foi comme un alignement mis en œuvre, et non comme une étiquette métaphysique flottant dans l’âme.
Le plan de Dieu comprend la guidance, les messagers, le discernement, la réponse.
Une fois la guidance reçue, invoquer « c’était la volonté de Dieu » pour excuser le rejet revient à refuser une carte, à s’enfoncer dans le désert et à blâmer la cartographie.
C’est pourquoi le verset poursuit en soulignant que les nations précédentes ont avancé la même excuse et ont tout de même dû en subir les conséquences.
L’histoire elle-même les contredit.
Dieu est pleinement souverain.
Les êtres humains sont pleinement responsables.
Ce chevauchement n’est pas une erreur. C’est l’épreuve.
Si cela vous semble « complexe et révélateur », tant mieux. Cela signifie que vous le lisez comme prévu, et non comme une simple machine à slogans.`;