var shdtxt=`Extrait de l'article sur la faim de Hamsun : « L'influence d'auteurs naturalistes tels qu'Émile Zola est manifeste dans le roman, tout comme son rejet de la tradition réaliste. » Comment cela se manifeste-t-il précisément dans l'œuvre ?
L'influence de Zola est omniprésente dans « La Faim », mais Hamsun s'approprie ses outils et en jette la moitié par la fenêtre.
Voici comment l'« influence » et le « rejet » se manifestent simultanément :
1. Influence du naturalisme : le corps comme piège.
Les naturalistes comme Zola aimaient montrer des êtres humains prisonniers de la biologie, de la pauvreté, de la faim, du sexe et de la déchéance sociale.
Hamsun s'inscrit pleinement dans cette perspective.
Son narrateur est affamé, hallucine, vend ses vêtements, grignote des copeaux de bois et oscille entre délire et réalité.
Son corps le manipule sans cesse, tel un marionnettiste cruel.
Cet aspect est typique du naturalisme : l'humain comme organisme, et non comme héros.
2. Mais rejet du réalisme : l'esprit Le monde se déforme.
Les réalistes ont tenté de présenter le monde « tel qu’il est ».
Hamsun en rit doucement (et un peu follement).
Au lieu de décrire la société ou les institutions, il plonge dans l’intimité des pensées du narrateur.
La réalité se déforme selon son degré de faim.
Il se montre noble un instant, mesquin l’instant d’après.
Il ment sans raison. Il donne de l’argent qu’il n’a pas.
Il essaie d’écrire comme un « appel de Dieu » et sombre aussitôt dans le désespoir.
Le monde est entièrement filtré par sa conscience déformée.
Voilà la rupture avec le réalisme. Les réalistes recherchent la clarté.
Hamsun vous plonge dans un esprit aux multiples facettes.
3. La misère naturaliste sans le moralisme naturaliste.
Zola aime expliquer les causes des événements : hérédité, environnement, dynamique des classes, forces sociales.
Hamsun n’a aucune envie de vous faire la leçon.
Il ne dit pas : « Le système l’a broyé. »
Il ne dit pas : « Il est victime de la société. »
Il ne dit pas : « Son traumatisme d’enfance l’a façonné. »
Il vous plonge simplement dans la psyché du personnage et vous fait souffrir avec lui.
Aucun mécanisme explicatif, juste l’expérience.
4. Le retournement de situation de « l’anti-héros comme sujet d’étude ».
Zola traitait ses personnages comme des sujets scientifiques.
Hamsun conserve le microscope. mais remplace la science par une psychologie instable.
Le narrateur devient une sorte de rêve fiévreux spirituel, une étude de :
• l'effondrement de l'ego. La mutation de l'orgueil. La honte qui tourbillonne comme de la fumée. L'identité qui se fissure sous le poids de la faim.
Ce n'est pas du réalisme social ; c'est de l'extrémisme intérieur.
5. Un langage qui refuse le réalisme.
Hamsun oscille entre : des détails sensoriels hyper-précis. Une comédie surréaliste. Une auto-illusion grandiose. Des réflexions philosophiques frénétiques. Une tendresse soudaine.
Les réalistes ne font pas cela.
Ils maintiennent la stabilité.
Hamsun écrit comme s'il avait injecté de la caféine et de l'angoisse dans sa plume.
Donc oui, influencé par le naturalisme…`;