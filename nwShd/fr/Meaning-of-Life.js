var shdtxt=`Quels films vous viennent à l’esprit si quelqu’un vous demande : « Comment puis-je trouver un sens et un but à la vie que je mène ? ! ».
La quête de sens et de but est l’un des thèmes les plus anciens de la narration.
Et différents réalisateurs l’ont mise en lumière à travers des registres très variés.
Tragédie, émerveillement, absurdité, voire comédie.
Voici quelques films qui viennent à l’esprit lorsque cette question est murmurée dans l’obscurité :
1. « Ikiru » (1952, Akira Kurosawa).
Un fonctionnaire apprend qu’il est en train de mourir et passe le temps qui lui reste à essayer d’accomplir un acte qui ait du sens.
Kurosawa fait passer la bureaucratie pour une lente agonie spirituelle, puis montre comment un simple terrain de jeux peut la racheter. 
2. « The Truman Show » (1998, Peter Weir).
Un homme découvre que toute sa vie n’est qu’un décor de télévision minutieusement élaboré.
C’est une parabole sur le sens imposé par opposition au sens choisi  –  le courage de sortir du scénario.
3. « The Tree of Life » (2011, Terrence Malick).
À mi-chemin entre la prière et le souvenir.
Le film commence par la mort d’un enfant, puis s’étend jusqu’à la naissance de l’univers.
Malick suggère que le sens n’est pas quelque chose que nous inventons, mais quelque chose que nous reconnaissons dans des moments de grâce.
4. « Un jour sans fin » (1993, Harold Ramis).
Une comédie qui se fait discrètement passer pour de la philosophie bouddhiste.
En revivant sans cesse la même journée, le protagoniste apprend que le sens ne naît pas de la nouveauté.
Mais du fait de s’ouvrir véritablement aux autres.
5. « Synecdoche, New York » (2008, Charlie Kaufman).
La tentative d’un dramaturge de recréer sa vie dans un entrepôt se transforme en un labyrinthe récursif de recherche de sens.
C’est à la fois douloureux, drôle et d’une honnêteté déchirante quant à notre obsession de nous comprendre nous-mêmes.
6. « Soul » (2020, Pixar).
Un musicien meurt avant de connaître le « succès ».
Et apprend que le sens de la vie ne réside peut-être pas dans ce que l’on « fait ».
Mais dans la profondeur avec laquelle on « vit ».
C’est de l’existentialisme pour tous les âges.
7. « Une vie cachée » (2019, Terrence Malick).
L’histoire vraie de Franz Jägerstätter, qui a refusé de prêter serment d’allégeance à Hitler.
Ici, le sens de la vie devient une clarté morale.
Vivre de manière significative, c’est choisir la vérité même lorsqu’elle est invisible.
8. « Les Ailes du désir » (1987, Wim Wenders).
Des anges planent au-dessus de Berlin, observateurs invisibles des peines et des joies humaines.
Jusqu’à ce que l’un d’entre eux aspire à « devenir » humain.
Le sens, suggère Wenders, réside dans l’incarnation, dans le contact, dans le risque.
9. « Into the Wild » (2007, Sean Penn).
Un homme abandonne la civilisation pour trouver la pureté dans la nature.
Son périple est à la fois une critique de la valeur matérielle et un rappel que l’isolement n’est jamais la réponse complète.
10. « It’s a Wonderful Life » (1946, Frank Capra).
Une assurance cinématographique que l’existence ordinaire de chacun « est » une vie qui a un sens.
Chacun de ces films apporte une réponse différente à la question « Qu’est-ce qui donne un sens à la vie ? ».
Certains mettent en avant l’amour.
D’autres, la création, le service, la prise de conscience ou le courage d’affronter l’absurdité.`;