var shdtxt=`Quels films vous viennent à l’esprit si quelqu’un vous demande « à quoi devrait ressembler la loyauté » ?
Au cinéma, la loyauté revêt de nombreux visages : tantôt noble, tantôt tragique, tantôt terrifiante.
En voici quelques-uns qui me viennent immédiatement à l’esprit.
La trilogie « Le Seigneur des Anneaux ».
Samwise Gamgee est l’incarnation la plus pure de la loyauté au cinéma.
Il ne se contente pas de suivre Frodon jusqu’au Mordor ;.
Il le porte lorsque Frodon ne peut plus marcher.
Sa loyauté n’est pas aveugle  –  elle est inébranlable, mise à l’épreuve dans la boue et le feu.
« Hachi : L'histoire d'un chien » (2009).
Un chien qui attend son maître tous les jours à la gare.
Bien longtemps après la mort de son maître.
La loyauté devient ici à la fois magnifique et déchirante.
« Le Parrain » (1972). La loyauté au sens mafieux relève davantage des serments de sang, de l’honneur et de la peur.
L’univers de Michael Corleone présente la loyauté comme un lien capable à la fois d’unir et de corrompre.
Ce qui soulève la question : êtes-vous loyal envers votre famille ou envers la morale ?
« Braveheart » (1995). La loyauté envers la patrie et les idéaux.
Ici, la loyauté est communautaire, forgée par des souffrances partagées.
« Harry Potter » (2001–2011). L’amitié du trio et le sacrifice de Dobby.
Les différents visages de la loyauté.
Parfois cachée, parfois coûteuse, mais toujours liée à l’amour.
« Il faut sauver le soldat Ryan » (1998).
Un peloton d’hommes risque sa vie pour sauver un seul soldat.
Ici, la loyauté va jusqu’à l’absurde.
Une vie vaut-elle plus que plusieurs autres ?
« Star Wars : L’Empire contre-attaque » (1980).
Han n’abandonne pas ses amis.
Chewbacca est inébranlable.
Et la trahison de Lando se transforme en loyauté, au prix fort.
La galaxie tourne autour de ces liens.
Ce qui est intéressant, c’est que la loyauté est rarement présentée comme « facile » au cinéma.
Les représentations les plus puissantes surviennent presque toujours lorsque la loyauté coûte quelque chose au personnage.
Du confort, de la sécurité, voire sa vie.
Si l’on prend du recul, la loyauté au cinéma s’apparente à un spectre.
De la tendre dévotion d’un animal de compagnie aux codes rigides de la mafia.
En passant par l’amour chaotique et sacrificiel entre des êtres humains imparfaits.
- La loyauté est étroitement liée à la foi.
- La foi en la réalisation d’un objectif fixé par des idéaux déjà proclamés et exprimés haut et fort.
- Ainsi, elle ne nécessite parfois pas la supervision de la personne avec laquelle on a conclu un pacte.
- Parfois, on peut confondre loyauté et routine.
- La manière dont nous gérons émotionnellement certaines situations ne sera peut-être pas toujours la même lorsque nous serons confrontés à des situations similaires à l’avenir.
- Mais le concept de loyauté, ou peut-être de cohérence, refait surface à ce moment-là.
- La loyauté peut également être liée au perfectionnisme.
- Un idéal abstrait dans votre esprit est parfois mis à l’épreuve par les aléas de la vie…
- La loyauté est donc ce qui nous guide vers des objectifs plus élevés.
- Pour apporter une perspective plus élevée à notre routine quotidienne.
- Existe-t-il alors une loyauté envers Dieu ?
- Dieu est indépendant de nos actions…
- Alors, où se manifeste la loyauté envers Dieu ?
La loyauté envers les personnes ou les causes est visible : on tient ses promesses, on est présent, on fait des sacrifices quand on est mis à l’épreuve.
Mais lorsque l’objet de la loyauté est Dieu  –  qui, comme vous le dites, est au-delà de tout besoin, au-delà de toute dette  –  nous entrons en terrain inconnu.
Dieu n’a pas besoin d’être surveillé, qu’on lui rappelle ses obligations, ni qu’on le rémunère.
Alors, que signifie être « fidèle » à Dieu ?
Il s’agit peut-être moins de faire quelque chose « pour » Dieu que de rester fidèle à la vision du bien, du vrai et du juste que Dieu incarne selon votre compréhension.
En d’autres termes : la loyauté envers Dieu se manifeste souvent dans la manière dont nous restons cohérents avec les idéaux que nous avons proclamés devant nous-mêmes et devant les autres.`;